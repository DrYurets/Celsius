inline bool isWindyCondition(float windSpeedMs) {
  return !isnan(windSpeedMs) && windSpeedMs >= 8.0f;
}

inline MeteoconGlyph makeGlyph(const uint8_t *rows, uint8_t width) {
  MeteoconGlyph g{rows, width, kMeteoconGlyphHeight};
  return g;
}

inline MeteoconGlyph meteoconByWmo(int32_t code, bool night = false) {
  if (code == 0 || code == 1) {
    return night ? makeGlyph(kMeteoconClearNight, kMeteoconClearNightWidth)
                 : makeGlyph(kMeteoconClearDay, kMeteoconClearDayWidth);
  }
  if (code == 2) {
    return night ? makeGlyph(kMeteoconPartlyNight, kMeteoconPartlyNightWidth)
                 : makeGlyph(kMeteoconPartlyDay, kMeteoconPartlyDayWidth);
  }
  if (code == 3) return makeGlyph(kMeteoconCloud, kMeteoconCloudWidth);
  if (code == 45 || code == 48) {
    return night ? makeGlyph(kMeteoconFogNight, kMeteoconFogNightWidth)
                 : makeGlyph(kMeteoconFogDay, kMeteoconFogDayWidth);
  }
  if (code == 95 || code == 96 || code == 99) return makeGlyph(kMeteoconThunder, kMeteoconThunderWidth);
  if ((code >= 80 && code <= 82)) return makeGlyph(kMeteoconShowers, kMeteoconShowersWidth);
  if ((code >= 51 && code <= 67)) return makeGlyph(kMeteoconRain, kMeteoconRainWidth);
  if ((code >= 71 && code <= 77) || (code >= 85 && code <= 86)) return makeGlyph(kMeteoconSnow, kMeteoconSnowWidth);
  return makeGlyph(kMeteoconCloud, kMeteoconCloudWidth);
}

inline MeteoconGlyph meteoconByWmoAndWind(int32_t code, float windSpeedMs, bool night = false) {
  if (isWindyCondition(windSpeedMs) && (code == 0 || code == 1 || code == 2 || code == 3)) {
    return makeGlyph(kMeteoconWind, kMeteoconWindWidth);
  }
  return meteoconByWmo(code, night);
}

