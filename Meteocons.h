inline const uint8_t *meteoconByWmo(int32_t code) {
  if (code == 0) return kMeteoconClear16;
  if (code == 1 || code == 2) return kMeteoconPartly16;
  if (code == 3) return kMeteoconCloud16;
  if (code == 45 || code == 48) return kMeteoconFog16;
  if (code == 95 || code == 96 || code == 99) return kMeteoconThunder16;
  if ((code >= 51 && code <= 67) || (code >= 80 && code <= 82)) return kMeteoconRain16;
  if ((code >= 71 && code <= 77) || (code >= 85 && code <= 86)) return kMeteoconSnow16;
  return kMeteoconCloud16;
}

